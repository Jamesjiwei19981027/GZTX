import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { PushPreferenceRow } from '../src/components/PushPreferenceSwitch';
import { pushTarget, readyPushTarget } from '../src/push/pushTarget';
import { bindNativePushSession, unregisterNativePush, subscribePushOpen } from '../src/push/nativePush';
import { apiRequest } from '../src/api/client';

assert.equal(renderToStaticMarkup(<PushPreferenceRow enabled={false} checked onChange={() => {}} />), '');
assert.match(renderToStaticMarkup(<PushPreferenceRow enabled checked onChange={() => {}} />), /手机推送/);
assert.match(renderToStaticMarkup(<PushPreferenceRow enabled checked onChange={() => {}} native />), /系统推送/);
assert.equal(pushTarget({ template_key: 'evidence.adopted', package_id: 7 }).params?.packageId, '7');
assert.equal(pushTarget({ template_key: 'progress.auto_write_alert', node_id: 9 }).screen, 'axis-progress');
assert.equal(pushTarget({ template_key: 'agent.report.submitted', report_id: 8, project_id: 2 }).params?.reportId, '8');
assert.equal(pushTarget({ template_key: 'project.report.aggregated', project_id: 2 }).screen, 'ai-project-aggregate');
assert.equal(pushTarget({ template_key: 'unknown' }).screen, 'messages-notifications');
assert.equal(readyPushTarget({ template_key: 'agent.report.submitted', report_id: 8, project_id: 2 }, [], false), null);
assert.equal(readyPushTarget({ template_key: 'agent.report.submitted', report_id: 8, project_id: 2 }, ['2'], true)?.screen, 'ai-report-detail');
assert.equal(readyPushTarget({ template_key: 'agent.report.submitted', report_id: 8, project_id: 2 }, [], true)?.screen, 'messages-notifications');

const surface = new EventTarget() as EventTarget & { FlutterBridge: { postMessage: (message: string) => void } };
const sent: Array<Record<string, unknown>> = [];
surface.FlutterBridge = { postMessage: message => sent.push(JSON.parse(message)) };
Object.assign(globalThis, { window: surface });
const requests: Array<{ path: string; init?: RequestInit }> = [];
let enabled = false;
const request = async (path: string, init?: RequestInit) => {
  requests.push({ path, init });
  return path === '/push/status' ? { enabled } : { enabled: true };
};
const flush = () => new Promise(resolve => setTimeout(resolve, 0));
const dispose = bindNativePushSession(request);
await flush();
assert.equal(sent.at(-1)?.enabled, false);
enabled = true;
surface.dispatchEvent(new Event('nativeRuntimeChange'));
await flush();
assert.equal(sent.at(-1)?.enabled, true);
const sessionId = sent.at(-1)?.session_id;
surface.dispatchEvent(new CustomEvent('nativePushRegistration', { detail: { registration_id: 'fake-rid', session_id: sessionId } }));
await flush();
const registration = requests.find(item => item.init?.method === 'POST');
assert.deepEqual(JSON.parse(String(registration?.init?.body)), { platform: 'android', registration_id: 'fake-rid', app_version: '2.0.0+2' });
assert.equal(sent.at(-1)?.type, 'pushRegistered', '登记成功后才确认恢复接收');
surface.dispatchEvent(new CustomEvent('nativePushOpen', { detail: { template_key: 'evidence.adopted', package_id: 7, session_id: sessionId } }));
let opened: unknown;
const unsubscribe = subscribePushOpen(extras => { opened = extras; });
assert.deepEqual(opened, { template_key: 'evidence.adopted', package_id: 7 });
await unregisterNativePush();
assert.equal(requests.at(-1)?.path, '/push/devices/fake-rid');
assert.equal(requests.at(-1)?.init?.method, 'DELETE');
assert.equal(sent.at(-1)?.enabled, false);
surface.dispatchEvent(new CustomEvent('nativePushRegistration', { detail: { registration_id: 'after-logout' } }));
await flush();
assert.equal(requests.at(-1)?.init?.method, 'DELETE');
unsubscribe();
dispose();
const hangingDispose = bindNativePushSession(async path => path === '/push/status' ? { enabled: true } : new Promise(() => {}));
await flush();
surface.dispatchEvent(new CustomEvent('nativePushRegistration', { detail: { registration_id: 'hanging-rid', session_id: sent.at(-1)?.session_id } }));
await flush();
const cleanup = unregisterNativePush();
assert.equal(sent.at(-1)?.enabled, false, '退出先停止宿主推送，不等待网络');
assert.equal(await Promise.race([cleanup.then(() => true), new Promise(resolve => setTimeout(() => resolve(false), 3500))]), true, '推送清理有界，不能卡住退出');
hangingDispose();
Object.assign(globalThis, { localStorage: { getItem: () => null }, fetch: async () => new Response(JSON.stringify({ enabled: true })) });
assert.deepEqual(await apiRequest('/push/status'), { enabled: true });
Object.assign(globalThis, { fetch: async () => new Response(JSON.stringify({ code: 200, data: { enabled: false } })) });
assert.deepEqual(await apiRequest('/push/status'), { enabled: false });
Object.assign(globalThis, { fetch: async () => new Response(null, { status: 204 }) });
assert.equal(await apiRequest('/push/devices/fake-rid', { method: 'DELETE' }), undefined);
console.log('JPush: unconfigured switch, payload routing, session registration/logout and cold click passed');
